"""
Project Euler Problem 12: Highly Divisible Triangular Number

The sequence of triangle numbers is generated by adding the natural numbers.
So the 7th triangle number would be 1 + 2 + 3 + 4 + 5 + 6 + 7 = 28.
The first ten terms would be:
    1, 3, 6, 10, 15, 21, 28, 36, 45, 55, ...

Let us list the factors of the first seven triangle numbers:
     1: 1
     3: 1, 3
     6: 1, 2, 3, 6
    10: 1, 2, 5, 10
    15: 1, 3, 5, 15
    21: 1, 3, 7, 21
    28: 1, 2, 4, 7, 14, 28

28 is the first triangle number to have over five divisors.
What is the value of the first triangle number to have over five hundred divisors?

URL: https://projecteuler.net/problem=12
"""

from functools import lru_cache

@lru_cache(maxsize=65536)
def count_divisors(n: int) -> int:
    """
    Computes the number of divisors d(n) using prime factorization:
    If n = p1^a1 * p2^a2 * ... * pk^ak, then d(n) = (a1 + 1)(a2 + 1)...(ak + 1).
    Time Complexity: O(sqrt(n))
    """
    if n <= 1:
        return 1

    count = 1
    d = 2
    temp = n
    while d * d <= temp:
        if temp % d == 0:
            exp = 0
            while temp % d == 0:
                exp += 1
                temp //= d
            count *= (exp + 1)
        d = 3 if d == 2 else d + 2

    if temp > 1:
        count *= 2

    return count

def highly_divisible_triangular_number(target_divisors: int = 500) -> int:
    """
    Finds the first triangle number Tn = n(n+1)/2 with more than target_divisors.
    
    Using the coprime property:
    - If n is even: gcd(n/2, n+1) = 1  => d(Tn) = d(n/2) * d(n+1)
    - If n is odd:  gcd(n, (n+1)/2) = 1 => d(Tn) = d(n) * d((n+1)/2)
    """
    n = 1
    while True:
        if n % 2 == 0:
            num_divs = count_divisors(n // 2) * count_divisors(n + 1)
        else:
            num_divs = count_divisors(n) * count_divisors((n + 1) // 2)

        if num_divs > target_divisors:
            return n * (n + 1) // 2
        n += 1

def solve(target_divisors: int = 500) -> int:
    """
    Solves Project Euler Problem 12 for the specified minimum number of divisors.
    Default: target_divisors = 500
    """
    return highly_divisible_triangular_number(target_divisors)

if __name__ == "__main__":
    result = solve(500)
    print(f"Project Euler Problem 12 Answer: {result}")
